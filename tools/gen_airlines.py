#!/usr/bin/env python3
"""
Generate core/receiver/.../enrich/Airlines.kt from two sources:

1. The Python receiver's `enrich/lookup.py:_AIRLINE_MAP` (the behavioral
   reference at --python-root, read-only — never edited by this script).
2. OpenFlights' airlines.dat (cached locally at tools/openflights_airlines.dat,
   ODbL-licensed: https://openflights.org — refresh with
   `curl -o tools/openflights_airlines.dat \\
     https://raw.githubusercontent.com/jpatokal/openflights/master/data/airlines.dat`),
   filtered to active airlines with a real 3-letter ICAO code.

_AIRLINE_MAP always wins on a conflicting ICAO prefix — it's the
already-verified-against-real-traffic table; OpenFlights only fills gaps it
doesn't cover. Re-run after changing the Python table or refreshing the cache.

    python tools/gen_airlines.py --python-root D:/SDR/adsb_v9_5
"""

from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

OUT = Path("core/receiver/src/main/kotlin/com/laviavi/adsbandroid/enrich/Airlines.kt")
OPENFLIGHTS_DAT = Path("tools/openflights_airlines.dat")

# airlines.dat columns: AirlineID,Name,Alias,IATA,ICAO,Callsign,Country,Active
OPENFLIGHTS_ICAO_COL = 4
OPENFLIGHTS_NAME_COL = 1
OPENFLIGHTS_ACTIVE_COL = 7


def load_openflights(path: Path) -> dict[str, str]:
    """ICAO -> name for active airlines with a real 3-letter ICAO code."""
    if not path.exists():
        return {}
    result: dict[str, str] = {}
    with open(path, encoding="utf-8", newline="") as fh:
        for row in csv.reader(fh):
            if len(row) <= max(OPENFLIGHTS_ICAO_COL, OPENFLIGHTS_NAME_COL, OPENFLIGHTS_ACTIVE_COL):
                continue
            if row[OPENFLIGHTS_ACTIVE_COL] != "Y":
                continue
            icao = row[OPENFLIGHTS_ICAO_COL].strip().upper()
            # Real ICAO airline designators are 3 ASCII A-Z letters (ICAO Doc
            # 8585) — a decoded Mode S callsign can't contain anything else,
            # so a non-ASCII code (a handful of OpenFlights rows have e.g.
            # Cyrillic) can never match and is just dead weight in the table.
            if len(icao) != 3 or not (icao.isascii() and icao.isalpha()):
                continue
            name = row[OPENFLIGHTS_NAME_COL].strip()
            if not name or name in ("Unknown", "Private flight"):
                continue
            result.setdefault(icao, name)
    return result


