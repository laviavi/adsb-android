def kotlin_string(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--python-root", required=True)
    ap.add_argument("--openflights-dat", default=str(OPENFLIGHTS_DAT))
    args = ap.parse_args(argv)

    sys.path.insert(0, str(Path(args.python_root).resolve()))
    from adsb_receiver.enrich.lookup import _AIRLINE_MAP as reference_table

    openflights_table = load_openflights(Path(args.openflights_dat))
    added = {k: v for k, v in openflights_table.items() if k not in reference_table}
    table = {**openflights_table, **reference_table}  # reference_table wins on conflict

    OUT.parent.mkdir(parents=True, exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(HEADER)
        for prefix in sorted(table):
            fh.write(f'        "{prefix}" to "{kotlin_string(table[prefix])}",\n')
        fh.write(FOOTER)

    print(
        f"wrote {OUT} — {len(table)} airlines "
        f"({len(reference_table)} reference + {len(added)} from OpenFlights)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
